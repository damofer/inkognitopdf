// Spec 006 + spec 004 (HU7): the audit page written into the PDF follows the
// interface language in use when it is generated, dates included.
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { setLang } from "../src/i18n";
import { auditDate, auditLines, auditPageText } from "../src/sign/multi";

const box: [number, number, number, number] = [0, 0, 595, 842];
const date = new Date(2026, 9, 14, 15, 30, 5);
const entry = {
  index: 0,
  name: "Ana Uno",
  email: "ana@example.com",
  date,
  mode: "pades" as const,
  certificateFingerprint: "AB:CD",
  documentHash: "0123ABCD",
};

describe("audit page in English", () => {
  beforeEach(() => setLang("en", false));
  afterEach(() => setLang("es", false));

  it("writes the header in English with the product name", () => {
    const texts = auditPageText(box, "contract.pdf").map((t) => t.text);
    expect(texts[0]).toBe("Signature log");
    expect(texts[1]).toBe("Document: contract.pdf");
    expect(texts[2]).toMatch(/^Generated by InkognitoPDF on each signer/);
    expect(texts.join(" ")).not.toMatch(/[áéíóúñ«»]|pdfcraft/i);
  });

  it("writes each row in English with a US date", () => {
    const lines = auditLines(entry);
    expect(lines[0]).toBe("1. Ana Uno <ana@example.com>");
    expect(lines[1]).toMatch(
      /^Date: 10\/14\/2026 03:30:05 PM \(UTC[+-]\d{2}:\d{2}\) {3}Type: digital signature \(PAdES\)$/,
    );
    expect(lines[2]).toBe("Certificate SHA-256: AB:CD");
    expect(lines[3]).toBe("Document SHA-256 before signing: 0123ABCD");
    expect(
      auditLines({
        ...entry,
        mode: "visual",
        certificateFingerprint: undefined,
      })[2],
    ).toBe("Certificate: none");
  });

  it("keeps the Spanish format when the language is Spanish", () => {
    setLang("es", false);
    expect(auditDate(date)).toMatch(
      /^14\/10\/2026 15:30:05 \(UTC[+-]\d{2}:\d{2}\)$/,
    );
    expect(auditPageText(box, "a.pdf")[0]!.text).toBe("Registro de firmas");
    expect(auditLines(entry)[1]).toMatch(/Tipo: firma digital \(PAdES\)$/);
  });
});
